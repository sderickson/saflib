import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { getMonorepoPackages } from "../workspace.ts";

/**
 * Renovate presets for product repos, published from saflib (public, so any
 * product's Renovate can read them):
 *
 * - `renovate/product.json` (generated): product defaults, plus every package
 *   saflib declares turned off. saflib is the source of truth for those
 *   versions; products get them by bumping saflib (`saf-monorepo saflib-bump`),
 *   never from their own Renovate PRs, which can't go green against saflib's
 *   overrides anyway.
 * - `renovate/product-automerge.json` (static, opt-in): Renovate merges
 *   low-risk product updates once CI is green.
 *
 * Products extend `github>sderickson/saflib//renovate/product`.
 */
export const PRODUCT_PRESET_PATH = "renovate/product.json";
export const PRODUCT_AUTOMERGE_PRESET_PATH = "renovate/product-automerge.json";

const DEP_FIELDS = [
  "dependencies",
  "devDependencies",
  "optionalDependencies",
  "peerDependencies",
] as const;

/** Template placeholders and workspace-only names, not registry packages. */
function isRegistryName(name: string): boolean {
  return (
    !name.startsWith("@saflib/") &&
    !name.startsWith("template-package-") &&
    !name.includes("__") &&
    !name.includes("#{")
  );
}

/** Registry packages any saflib package declares, plus saflib's root overrides. */
export function collectSaflibOwnedPackages(saflibDir: string): string[] {
  const names = new Set<string>();
  const { monorepoPackageJsons } = getMonorepoPackages(saflibDir);
  const workspaceNames = new Set(Object.keys(monorepoPackageJsons));
  // Includes saflib's root package.
  const packageJsons = Object.values(monorepoPackageJsons) as unknown as Record<
    string,
    Record<string, unknown> | undefined
  >[];
  for (const pkg of packageJsons) {
    for (const field of DEP_FIELDS) {
      for (const name of Object.keys(pkg[field] ?? {})) {
        if (!workspaceNames.has(name) && isRegistryName(name)) names.add(name);
      }
    }
  }
  const root = JSON.parse(
    readFileSync(path.join(saflibDir, "package.json"), "utf8"),
  ) as { overrides?: Record<string, unknown> };
  for (const name of Object.keys(root.overrides ?? {})) {
    if (isRegistryName(name)) names.add(name);
  }
  return [...names].sort();
}

/** The generated product preset for `saflibDir`. */
export function buildProductPreset(saflibDir: string): Record<string, unknown> {
  return {
    $schema: "https://docs.renovatebot.com/renovate-schema.json",
    description:
      "Renovate defaults for SAF product repos. Generated by `saf-monorepo renovate-preset` from saflib's package.json files; don't edit by hand.",
    timezone: "America/Los_Angeles",
    minimumReleaseAge: "3 days",
    internalChecksFilter: "strict",
    osvVulnerabilityAlerts: true,
    vulnerabilityAlerts: { labels: ["security"], minimumReleaseAge: null },
    rebaseWhen: "behind-base-branch",
    packageRules: [
      {
        groupName: "GitHub Actions",
        matchManagers: ["github-actions"],
      },
      {
        groupName: "Docker images",
        matchDatasources: ["docker"],
      },
      {
        description:
          "saflib owns these versions. Products get them by bumping saflib (saf-monorepo saflib-bump), which copies saflib's overrides and re-resolves the lockfile.",
        matchManagers: ["npm"],
        matchPackageNames: collectSaflibOwnedPackages(saflibDir),
        enabled: false,
      },
      {
        description: "saflib's own packages come with the submodule.",
        matchPackageNames: ["@saflib/{/,}**"],
        enabled: false,
      },
      {
        description:
          "Node follows saflib (its base images and CI); move a product's Node after saflib's.",
        matchPackageNames: ["node"],
        matchDatasources: ["docker", "node-version"],
        enabled: false,
      },
    ],
  };
}

/** Opt-in auto-merge for low-risk product updates (saflib-owned ones are off already). */
export const PRODUCT_AUTOMERGE_PRESET = {
  $schema: "https://docs.renovatebot.com/renovate-schema.json",
  description:
    "Opt-in for SAF product repos: Renovate merges low-risk updates itself once CI is green (Actions and image digests/patches, npm patches of product-only packages). Majors and minors still wait for a person.",
  automergeType: "pr",
  // Renovate merges on its next run; works on private repos without branch
  // protection, unlike GitHub's native auto-merge.
  platformAutomerge: false,
  packageRules: [
    {
      matchManagers: ["github-actions"],
      matchUpdateTypes: ["digest", "pin", "pinDigest", "patch"],
      automerge: true,
    },
    {
      matchDatasources: ["docker"],
      matchUpdateTypes: ["digest", "patch"],
      automerge: true,
    },
    {
      matchManagers: ["npm"],
      matchUpdateTypes: ["patch"],
      automerge: true,
    },
  ],
};

function serialize(preset: unknown): string {
  return `${JSON.stringify(preset, null, 2)}\n`;
}

/**
 * Write (or with `check`, compare) both presets. Returns the paths that were
 * out of date.
 */
export function writeRenovatePresets(
  saflibDir: string,
  options: { check?: boolean } = {},
): string[] {
  const stale: string[] = [];
  const outputs: [string, string][] = [
    [PRODUCT_PRESET_PATH, serialize(buildProductPreset(saflibDir))],
    [PRODUCT_AUTOMERGE_PRESET_PATH, serialize(PRODUCT_AUTOMERGE_PRESET)],
  ];
  for (const [rel, contents] of outputs) {
    const file = path.join(saflibDir, rel);
    const current = existsSync(file) ? readFileSync(file, "utf8") : undefined;
    if (current === contents) continue;
    stale.push(rel);
    if (!options.check) {
      mkdirSync(path.dirname(file), { recursive: true });
      writeFileSync(file, contents);
    }
  }
  return stale;
}
