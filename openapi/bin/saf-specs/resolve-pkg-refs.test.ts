import { describe, expect, it } from "vitest";
import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  findSchemaNameForFile,
  rewriteBundledExternalRefs,
  rewritePkgRefs,
  resolvePkgResource,
} from "./resolve-pkg-refs.ts";
import { rewriteExternalSchemaTypes } from "./rewrite-external-types.ts";

const fixturesDir = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "fixtures",
);
const parentDir = path.join(fixturesDir, "parent");
const offshootDir = path.join(fixturesDir, "offshoot");

describe("resolvePkgResource", () => {
  it("resolves pkg: openapi.yaml via package exports", () => {
    const { packageName, absolutePath } = resolvePkgResource(
      "pkg:@fixture/offshoot-spec/openapi.yaml",
      parentDir,
    );
    expect(packageName).toBe("@fixture/offshoot-spec");
    expect(absolutePath).toBe(path.join(offshootDir, "openapi.yaml"));
  });

  it("falls back to package-root relative path for source YAML", () => {
    const { absolutePath } = resolvePkgResource(
      "pkg:@fixture/offshoot-spec/schemas/widget.yaml",
      parentDir,
    );
    expect(absolutePath).toBe(path.join(offshootDir, "schemas/widget.yaml"));
  });
});

describe("findSchemaNameForFile", () => {
  it("maps a schema file to its component name", () => {
    expect(
      findSchemaNameForFile(
        path.join(offshootDir, "openapi.yaml"),
        path.join(offshootDir, "schemas/widget.yaml"),
      ),
    ).toBe("Widget");
  });
});

describe("rewritePkgRefs", () => {
  it("rewrites pkg: refs to absolute paths and records provenance", () => {
    const result = rewritePkgRefs({
      entryFile: "openapi.yaml",
      cwd: parentDir,
    });
    try {
      const rewritten = readFileSync(result.rewrittenEntryPath, "utf8");
      expect(rewritten).not.toContain("pkg:");
      expect(rewritten).toContain(path.join(offshootDir, "openapi.yaml"));
      expect(result.externalSchemas.get("Widget")).toEqual({
        packageName: "@fixture/offshoot-spec",
        schemaName: "Widget",
      });
    } finally {
      result.cleanup();
    }
  });
});

describe("rewritePkgRefs with nested pkg: refs", () => {
  it("rewrites pkg: refs inside other packages' schemas", () => {
    const result = rewritePkgRefs({
      entryFile: "openapi.yaml",
      cwd: parentDir,
    });
    try {
      const files: string[] = [];
      const walk = (dir: string) => {
        for (const entry of readdirSync(dir, { withFileTypes: true })) {
          const full = path.join(dir, entry.name);
          if (entry.isDirectory()) walk(full);
          else files.push(full);
        }
      };
      walk(result.tempDir);
      const gadget = files.find((f) => f.endsWith("schemas/gadget.yaml"));
      expect(gadget).toBeDefined();
      expect(readFileSync(gadget!, "utf8")).not.toContain("pkg:");
      for (const file of files) {
        expect(readFileSync(file, "utf8"), file).not.toContain("pkg:");
      }
    } finally {
      result.cleanup();
    }
  });

  it("records provenance only from the generating package's documents", () => {
    const result = rewritePkgRefs({
      entryFile: "openapi.yaml",
      cwd: parentDir,
    });
    try {
      expect(result.externalSchemas.has("Gadget")).toBe(true);
      // `Error` is only referenced from inside the offshoot's gadget.yaml.
      expect(result.externalSchemas.has("Error")).toBe(false);
    } finally {
      result.cleanup();
    }
  });
});

describe("rewriteBundledExternalRefs", () => {
  it("rewrites temp-dir file refs to package-relative paths", () => {
    const tempDir = path.join("/tmp", "saf-specs-test");
    const refPath = path.join(
      tempDir,
      "routes/__group-name__/__target-name__.yaml",
    );
    const doc = {
      paths: {
        "__url-path__": {
          __method__: {
            $ref: `${refPath}#/stubOperation`,
          },
        },
      },
    };
    const out = rewriteBundledExternalRefs(doc, {
      tempDir,
      packageRoot: tempDir,
    }) as typeof doc;
    expect(out.paths["__url-path__"]["__method__"].$ref).toBe(
      "./routes/__group-name__/__target-name__.yaml#/stubOperation",
    );
  });
});

describe("rewriteExternalSchemaTypes", () => {
  it("replaces external schema bodies with import aliases", () => {
    const dts = `/**
 * This file was auto-generated by openapi-typescript.
 */
export interface components {
    schemas: {
        LocalThing: {
            widget?: components["schemas"]["Widget"];
        };
        Widget: {
            id: string;
            label?: string;
        };
    };
}
`;
    const external = new Map([
      [
        "Widget",
        {
          packageName: "@fixture/offshoot-spec",
          schemaName: "Widget",
        },
      ],
    ]);
    const out = rewriteExternalSchemaTypes(dts, external);
    expect(out).toContain(
      'import type { Widget as _Ext0_Widget } from "@fixture/offshoot-spec/schemas/Widget";',
    );
    expect(out).toContain("Widget: _Ext0_Widget");
    expect(out).not.toMatch(/Widget:\s*\{\s*id:/);
  });
});

describe("rewritePkgRefs with a pkg: ref to its own package", () => {
  it("does not record the package's own schemas as external", () => {
    const result = rewritePkgRefs({
      entryFile: "openapi.yaml",
      cwd: offshootDir,
    });
    try {
      expect(
        [...result.externalSchemas.values()].map((p) => p.packageName),
      ).not.toContain("@fixture/offshoot-spec");
    } finally {
      result.cleanup();
    }
  });
});
